export function getVerifiedEmployerSources(): EmployerSource[] {
  return VERIFIED_EMPLOYER_REGISTRY.filter((s) => s.status === 'verified')
}

export function findEmployerSource(token: string): EmployerSource | undefined {
  return VERIFIED_EMPLOYER_REGISTRY.find(
    (s) => s.boardToken.toLowerCase() === token.toLowerCase()
  )
}
